    # KỊCH BẢN 12: Benchmark p50/p95 latency trên 3 phiên, outbox lag, 0 sync error
    # --------------------------------------------------------------------------
    def test_scenario_12_latency_p50_p95_three_sessions_benchmark(self) -> None:
        cg_token = self.auth.create_session(self.auth.authenticate_user("user_care_001"))

        session_results: List[Dict[str, Any]] = []

        for session_idx in range(1, 4):
            cg_sse = sse_hub.register_client("user_care_001", "caregiver")
            latencies_ms: List[float] = []
            sync_errors = 0

            # Chạy 20 sự kiện trong mỗi phiên
            for event_idx in range(20):
                obs_payload = {
                    "items": [
                        {
                            "code": "bp_systolic" if event_idx % 2 == 0 else "bp_diastolic",
                            "value": 115.0 + event_idx,
                            "unit": "mmHg",
                        }
                    ]
                }

                t_commit_start = time.perf_counter()
                # 1. API request & commit (server ack)
                code, res = self.router.handle_request("POST", "/api/patients/patient_001/observations", {}, obs_payload, cg_token)
                if code != 201:
                    sync_errors += 1
                    continue

                # 2. Worker relay trigger & dispatch
                self.relay.process_pending_events()

                # 3. Web client nhận qua SSE
                try:
                    event = cg_sse.queue.get(timeout=1.0)
                    t_web_received = time.perf_counter()
                    lat_ms = (t_web_received - t_commit_start) * 1000.0
                    latencies_ms.append(lat_ms)
                except Exception:
                    sync_errors += 1

            # Tính p50 và p95 cho phiên
            latencies_ms.sort()
            p50 = latencies_ms[int(len(latencies_ms) * 0.50)]
            p95 = latencies_ms[int(len(latencies_ms) * 0.95)]
            metrics = self.relay.get_metrics()

            session_results.append({
                "session": session_idx,
                "event_count": len(latencies_ms),
                "p50_ms": round(p50, 2),
                "p95_ms": round(p95, 2),
                "outbox_lag_ms": metrics["last_lag_ms"],
                "sync_errors": sync_errors,
            })

            sse_hub.unregister_client(cg_sse.client_id)

        # In kết quả benchmark để đưa vào báo cáo
        print("\n" + "=" * 70)
        print("KẾT QUẢ ĐO ĐẠC HIỆU NĂNG REALTIME QUA 3 PHIÊN ĐỘC LẬP (MỤC 9.12)")
        print(f"Hệ điều hành: {platform.system()} {platform.release()} ({platform.machine()})")
        print(f"Python: {platform.python_version()}")
        print("-" * 70)
        for r in session_results:
            print(f"Phiên {r['session']}: Số sự kiện = {r['event_count']}, p50 = {r['p50_ms']}ms, p95 = {r['p95_ms']}ms, Outbox Lag = {r['outbox_lag_ms']}ms, Lỗi = {r['sync_errors']}")
            self.assertEqual(r["sync_errors"], 0, f"Phiên {r['session']} không được có lỗi đồng bộ")
            self.assertLess(r["p95_ms"], 5000.0, f"Phiên {r['session']} p95 {r['p95_ms']}ms phải <= 5000ms")
        print("=" * 70)


