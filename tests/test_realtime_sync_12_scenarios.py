    # --------------------------------------------------------------------------
    def test_scenario_01_three_clients_one_touch_medication_sync(self) -> None:
        # 1. Mở 3 client
        elder_client = ElderSyncClient(self.db, patient_id="patient_001", queue_dir=self.queue_dir)
        cg_sse = sse_hub.register_client("user_care_001", "caregiver")
        doc_sse = sse_hub.register_client("user_doc_001", "clinician")

        # Lấy một liều thuốc hôm nay
        snapshot = elder_client.get_today_snapshot()
        self.assertGreater(len(snapshot["doses"]), 0, "Phải có liều thuốc được lên lịch hôm nay")
        target_occ = snapshot["doses"][0]
        occ_id = target_occ["occurrence_id"]

        t_start = time.perf_counter()

        # 2. Người già bấm một chạm 'Đã uống'
        cid = f"test_click_{uuid.uuid4().hex[:8]}"
        res = elder_client.confirm_dose_taken(occ_id, action="self_reported_taken", client_event_id=cid)
        self.assertEqual(res["status"], "processed")

        # 3. Worker relay xử lý và dispatch SSE
        processed = self.relay.process_pending_events()
        self.assertGreater(processed, 0, "Outbox event phải được xử lý")

        # 4. Cả hai web nhận tín hiệu qua SSE
        cg_event = cg_sse.queue.get(timeout=2.0)
        doc_event = doc_sse.queue.get(timeout=2.0)
        t_delivered = time.perf_counter()

        latency_sec = t_delivered - t_start
        self.assertLess(latency_sec, 5.0, f"Độ trễ {latency_sec:.4f}s phải <= 5 giây p95")
        self.assertEqual(cg_event["type"], "medication.dose_changed")
        self.assertEqual(doc_event["type"], "medication.dose_changed")
        self.assertEqual(cg_event["patient_id"], "patient_001")

        # Payload broadcast chỉ chứa metadata tối thiểu, KHÔNG chứa hồ sơ nhạy cảm
        self.assertNotIn("prescription_text", cg_event)
        self.assertNotIn("patient_history", cg_event)

        # 5. Cả hai web refetch API có quyền kiểm tra trạng thái
        doc_token = self.auth.create_session(self.auth.authenticate_user("user_doc_001"))
        code, doc_res = self.router.handle_request("GET", "/api/patients/patient_001/medication/doses", {}, {}, doc_token)
        self.assertEqual(code, 200)
        updated_dose = next(d for d in doc_res["doses"] if d["occurrence_id"] == occ_id)
        self.assertEqual(updated_dose["state"], "CONFIRMED")
        self.assertIn("self_reported_taken", updated_dose["action_notes"])
        self.assertIn("tự khai báo", doc_res["note"])

        # 6. Người già bấm lặp lại với cùng event ID -> Không tạo bản ghi trùng
        with self.db.connect() as conn:
            cnt_before = conn.fetchone("SELECT COUNT(*) as cnt FROM dose_events WHERE occurrence_id = ?", (occ_id,))["cnt"]

        elder_client.confirm_dose_taken(occ_id, action="self_reported_taken", client_event_id=cid)
        elder_client.flush_offline_queue()

        with self.db.connect() as conn:
            cnt_after = conn.fetchone("SELECT COUNT(*) as cnt FROM dose_events WHERE occurrence_id = ?", (occ_id,))["cnt"]
        self.assertEqual(cnt_before, cnt_after, "Bấm lặp lại với cùng client_event_id không được tạo thêm dose_event")

