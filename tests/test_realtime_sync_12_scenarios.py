    # KỊCH BẢN 3: Camera xác nhận đủ 10/10 lần -> hoàn thành; 9/10 chưa hoàn thành; chống lặp rep ID
    # --------------------------------------------------------------------------
    def test_scenario_03_camera_target_10_reps_auto_completion(self) -> None:
        sess_id = f"sess_test_{uuid.uuid4().hex[:8]}"
        today_iso = date.today().isoformat()
        with self.db.connect() as conn:
            conn.execute(
                """
                INSERT INTO rehab_sessions (session_id, patient_id, plan_id, plan_version, local_date, started_at, ended_at, target_count_snapshot, verified_count, completion_source, status, algorithm_version, notes)
                VALUES (?, 'patient_001', 'rp_001', 1, ?, ?, NULL, 10, 0, 'camera', 'in_progress', 'MediaPipe-Pose-FSM-v1.0', 'Kiểm thử đếm tự động')
                """,
                (sess_id, today_iso, datetime.now(UTC).isoformat()),
            )
            conn.commit()

        elder_client = ElderSyncClient(self.db, patient_id="patient_001", queue_dir=self.queue_dir)
        cg_sse = sse_hub.register_client("user_care_001", "caregiver")

        # Gửi 9 lần lặp
        for i in range(1, 10):
            rep_cid = f"rep_evt_{i}_{uuid.uuid4().hex[:6]}"
            elder_client.enqueue_event(
                "rehab.rep",
                {"session_id": sess_id, "rep_number": i, "score": 96.0, "exercise_id": "arm_raise"},
                client_event_id=rep_cid,
            )

        elder_client.flush_offline_queue()
        self.relay.process_pending_events()

        # Kiểm tra tại 9 lần: chưa hoàn thành
        with self.db.connect() as conn:
            sess_9 = conn.fetchone("SELECT status, verified_count FROM rehab_sessions WHERE session_id = ?", (sess_id,))
            self.assertEqual(sess_9["verified_count"], 9)
            self.assertNotEqual(sess_9["status"], "camera_verified_completed")

        # Thử gửi lại lần 9 với CÙNG event_id -> Chống tăng số đếm (idempotency)
        elder_client.enqueue_event(
            "rehab.rep",
            {"session_id": sess_id, "rep_number": 9, "score": 96.0, "exercise_id": "arm_raise"},
            client_event_id=rep_cid,  # duplicate ID
        )
        elder_client.flush_offline_queue()
        with self.db.connect() as conn:
            sess_dup = conn.fetchone("SELECT verified_count FROM rehab_sessions WHERE session_id = ?", (sess_id,))
            self.assertEqual(sess_dup["verified_count"], 9, "Retry cùng client_event_id không được tăng verified_count")

        # Gửi lần thứ 10
        rep_10_cid = f"rep_evt_10_{uuid.uuid4().hex[:6]}"
        elder_client.enqueue_event(
            "rehab.rep",
            {"session_id": sess_id, "rep_number": 10, "score": 98.0, "exercise_id": "arm_raise"},
            client_event_id=rep_10_cid,
        )
        elder_client.flush_offline_queue()
        self.relay.process_pending_events()

        # Kiểm tra sau lần 10: Tự chuyển trạng thái camera_verified_completed
        with self.db.connect() as conn:
            sess_10 = conn.fetchone("SELECT status, verified_count, ended_at FROM rehab_sessions WHERE session_id = ?", (sess_id,))
            self.assertEqual(sess_10["verified_count"], 10)
            self.assertEqual(sess_10["status"], "camera_verified_completed")
            self.assertIsNotNone(sess_10["ended_at"])

        # Web caregiver nhận tín hiệu hoàn thành
        events = []
        while not cg_sse.queue.empty():
            events.append(cg_sse.queue.get_nowait())
        self.assertTrue(any(e.get("type") == "rehab.session_updated" for e in events))

