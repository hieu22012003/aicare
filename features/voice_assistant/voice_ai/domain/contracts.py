"""
Domain Contracts, Enums, and Data Transfer Objects (DTOs) for Voice AI.
Strictly implements the Intent Taxonomy and Lifecycle States defined in
VOICE_AI_IMPLEMENTATION_PLAN.md.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from enum import Enum
from typing import Any, Dict, List, Optional


class IntentType(str, Enum):
    """Normalized Intent Enums supported by the Voice AI System."""
    DOCTOR_ASSISTANCE = "DOCTOR_ASSISTANCE"
    HEALTH_REPORT = "HEALTH_REPORT"
    MEDICATION_CONFIRM = "MEDICATION_CONFIRM"
    MEDICATION_NOT_TAKEN = "MEDICATION_NOT_TAKEN"
    MEDICATION_GUIDANCE = "MEDICATION_GUIDANCE"
    MEDICATION_REMIND_LATER = "MEDICATION_REMIND_LATER"
    REHABILITATION_START = "REHABILITATION_START"
    GAME_LAUNCH = "GAME_LAUNCH"
    MUSIC_PLAY = "MUSIC_PLAY"
    MUSIC_PAUSE = "MUSIC_PAUSE"
    MUSIC_STOP = "MUSIC_STOP"
    UNKNOWN = "UNKNOWN"
    CLARIFY = "CLARIFY"


class IntentPriority(str, Enum):
    """Backend-assigned priority level for orchestrating multi-intent utterances."""
    P1 = "P1"  # Urgent Doctor Assistance / SOS
    P2 = "P2"  # Health observation / Symptoms triage
    P3 = "P3"  # Medication adherence confirmation / guidance
    P4 = "P4"  # Non-clinical actions (Rehab, Games, Music playback)
    NONE = "NONE"  # Unknown / Clarification needed


# Canonical Priority mapping: Backend determines priority, never trusted from LLM
INTENT_PRIORITY_MAP: Dict[IntentType, IntentPriority] = {
    IntentType.DOCTOR_ASSISTANCE: IntentPriority.P1,
    IntentType.HEALTH_REPORT: IntentPriority.P2,
    IntentType.MEDICATION_CONFIRM: IntentPriority.P3,
    IntentType.MEDICATION_NOT_TAKEN: IntentPriority.P3,
    IntentType.MEDICATION_GUIDANCE: IntentPriority.P3,
    IntentType.MEDICATION_REMIND_LATER: IntentPriority.P3,
    IntentType.REHABILITATION_START: IntentPriority.P4,
    IntentType.GAME_LAUNCH: IntentPriority.P4,
    IntentType.MUSIC_PLAY: IntentPriority.P4,
    IntentType.MUSIC_PAUSE: IntentPriority.P4,
    IntentType.MUSIC_STOP: IntentPriority.P4,
    IntentType.UNKNOWN: IntentPriority.NONE,
    IntentType.CLARIFY: IntentPriority.NONE,
}


class ExecutionStatus(str, Enum):
    """Per-intent execution lifecycle state."""
    RECEIVED = "RECEIVED"
    VALIDATING = "VALIDATING"
    NEEDS_CLARIFICATION = "NEEDS_CLARIFICATION"
    NEEDS_CONFIRMATION = "NEEDS_CONFIRMATION"
    READY = "READY"
    EXECUTING = "EXECUTING"
    COMPLETED = "COMPLETED"
    FAILED = "FAILED"
    CANCELLED = "CANCELLED"


class AssistanceLifecycle(str, Enum):
    """Separate lifecycle state for Doctor Assistance requests."""
    PENDING_ACK = "PENDING_ACK"
    ACKNOWLEDGED = "ACKNOWLEDGED"
    IN_PROGRESS = "IN_PROGRESS"
    RESOLVED = "RESOLVED"
    ESCALATED = "ESCALATED"


class RedFlagSeverity(str, Enum):
    """Severity classification for clinical triage of reported symptoms."""
    NONE = "NONE"
    LOW = "LOW"
    MODERATE = "MODERATE"
    CRITICAL = "CRITICAL"


@dataclass
class TranscriptResult:
    """Result returned by Speech-to-Text (ASR) layer."""
    transcript: str
    language: str = "vi"
    duration_seconds: float = 0.0
    confidence: float = 1.0
    is_final: bool = True
    metadata: Dict[str, Any] = field(default_factory=dict)


@dataclass
class VoiceIntent:
    """Validated intent extracted from transcript."""
    type: IntentType
    entities: Dict[str, Any] = field(default_factory=dict)
    evidence_span: str = ""
    requires_clarification: bool = False
    clarification_prompt: Optional[str] = None
    priority: IntentPriority = IntentPriority.NONE
    reason: Optional[str] = None
    risk_flags: List[str] = field(default_factory=list)

    def __post_init__(self) -> None:
        if isinstance(self.type, str):
            self.type = IntentType(self.type)
        if self.priority == IntentPriority.NONE:
            self.priority = INTENT_PRIORITY_MAP.get(self.type, IntentPriority.NONE)


@dataclass
class SemanticResult:
    """Consolidated semantic interpretation output."""
    schema_version: str = "1.0"
    language: str = "vi"
    intents: List[VoiceIntent] = field(default_factory=list)
    raw_model_output: Optional[str] = None
    model_id: str = "gemini-2.5-flash"
    prompt_version: str = "v1.0"
    requires_clarification: bool = False
    clarification_question: Optional[str] = None
    reason: Optional[str] = None
    risk_flags: List[str] = field(default_factory=list)


@dataclass
class SafetySignal:
    """Signals generated by deterministic pre-LLM safety detector."""
    is_urgent_assistance: bool = False
    is_red_flag_health: bool = False
    red_flag_severity: RedFlagSeverity = RedFlagSeverity.NONE
    urgency_reason: Optional[str] = None
    matched_keywords: List[str] = field(default_factory=list)
    has_negation: bool = False
    suggested_action: Optional[str] = None


@dataclass
class ActionPayload:
    """Safe, allowlisted client action returned to GUI."""
    action_type: str  # e.g., 'game.open', 'media.play', 'media.pause', 'media.stop'
    parameters: Dict[str, Any] = field(default_factory=dict)


@dataclass
class IntentExecutionResult:
    """Result of dispatching and executing a single intent."""
    intent_id: str
    intent_type: IntentType
    status: ExecutionStatus
    priority: IntentPriority
    aggregate_id: Optional[str] = None
    aggregate_type: Optional[str] = None
    error_code: Optional[str] = None
    error_message: Optional[str] = None
    client_action: Optional[ActionPayload] = None
    message_to_elder: Optional[str] = None


@dataclass
class OrchestratorExecutionResult:
    """Consolidated execution output for an entire voice interaction."""
    interaction_id: str
    session_id: str
    patient_id: str
    timestamp_utc: str
    transcript: str
    safety_signal: SafetySignal
    intent_results: List[IntentExecutionResult] = field(default_factory=list)
    overall_status: ExecutionStatus = ExecutionStatus.COMPLETED
    response_speech_text: str = ""
    clarification_question: Optional[str] = None
    trace_summary: Optional[Dict[str, Any]] = None

