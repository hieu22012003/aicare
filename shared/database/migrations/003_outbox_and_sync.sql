-- ==============================================================================
-- MIGRATION 003: DURABLE OUTBOX EVENTS & CLIENT SYNC INBOX
-- For Near Real-Time Synchronization between Elder App and Web Portals
-- Compatible with PostgreSQL and SQLite
-- ==============================================================================

-- 1. BẢNG OUTBOX EVENTS (GHI ĐỒNG THỜI VỚI NGHIỆP VỤ TRONG CÙNG TRANSACTION)
CREATE TABLE IF NOT EXISTS outbox_events (
    event_id VARCHAR(64) PRIMARY KEY,
    patient_id VARCHAR(64) NOT NULL,
    event_type VARCHAR(64) NOT NULL,            -- e.g. 'medication.dose_changed', 'rehab.session_updated', 'health.observation_created', etc.
    aggregate_type VARCHAR(64) NOT NULL,        -- e.g. 'dose_occurrence', 'rehab_session', 'measurement_group', 'prescription', etc.
    aggregate_id VARCHAR(64) NOT NULL,          -- e.g. occurrence_id, session_id, group_id, prescription_id
    aggregate_version INTEGER NOT NULL DEFAULT 1,
    occurred_at TEXT NOT NULL,                  -- ISO 8601 UTC timestamp of occurrence
    actor_id VARCHAR(64),                       -- User ID who performed the action (nullable for system/camera)
    source VARCHAR(64) NOT NULL DEFAULT 'elder_app', -- 'elder_app', 'camera_ai', 'web_caregiver', 'web_clinician', 'scheduler'
    payload_minimal TEXT NOT NULL DEFAULT '{}', -- Minimal JSON payload: only IDs/state for client to refetch
    processed_at TEXT,                          -- ISO 8601 UTC when processed by relay worker (NULL if pending)
    attempts INTEGER NOT NULL DEFAULT 0,        -- Number of delivery/relay attempts
    last_error TEXT,                            -- Last error message if failed
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id) ON DELETE RESTRICT
);

-- 2. BẢNG SYNC INBOX (CHỐNG LẶP / IDEMPOTENCY CHO CLIENT VÀ CAMERA GỬI LẠI)
CREATE TABLE IF NOT EXISTS sync_inbox (
    client_event_id VARCHAR(64) PRIMARY KEY,    -- Unique ID generated by client device or camera
    patient_id VARCHAR(64) NOT NULL,
    source_device_id VARCHAR(64) DEFAULT 'desktop_01',
    received_at TEXT NOT NULL,                  -- ISO 8601 UTC when server received
    status VARCHAR(32) NOT NULL DEFAULT 'PROCESSED', -- 'RECEIVED', 'PROCESSED', 'DUPLICATE', 'FAILED'
    canonical_event_id VARCHAR(64),             -- Mapped canonical event_id in outbox_events or business tables
    error_code VARCHAR(64),
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id) ON DELETE RESTRICT
);

-- 3. BẢNG THIẾT BỊ VÀ PHIÊN ỨNG DỤNG NGƯỜI GIÀ (DEVICE_SESSIONS)
CREATE TABLE IF NOT EXISTS device_sessions (
    device_id VARCHAR(64) PRIMARY KEY,
    patient_id VARCHAR(64) NOT NULL,
    app_version VARCHAR(32) NOT NULL DEFAULT '1.0.0',
    last_seen_at TEXT NOT NULL,
    is_online INTEGER NOT NULL DEFAULT 1 CHECK(is_online IN (0, 1)),
    FOREIGN KEY (patient_id) REFERENCES patients(patient_id) ON DELETE CASCADE
);

-- ==============================================================================
-- INDEX TỐI ƯU TRUY VẤN CHO OUTBOX WORKER VÀ CLIENT SYNC
-- ==============================================================================
CREATE INDEX IF NOT EXISTS idx_outbox_unprocessed ON outbox_events(processed_at, occurred_at);
CREATE INDEX IF NOT EXISTS idx_outbox_patient_time ON outbox_events(patient_id, occurred_at DESC);
CREATE INDEX IF NOT EXISTS idx_sync_inbox_patient ON sync_inbox(patient_id, received_at DESC);

